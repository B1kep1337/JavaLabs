    private void jMenuItemLoadbinActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItemLoadbinActionPerformed
    JFileChooser f = new JFileChooser();
    FileNameExtensionFilter filter = new FileNameExtensionFilter("Binary file (*.bin)", "bin");
    f.setFileFilter(filter);
    f.showOpenDialog(null);
    
    File file = f.getSelectedFile(); 
    
    try(ObjectInputStream in = new ObjectInputStream(new BufferedInputStream(new FileInputStream(file))))
    {
        linkInteg = (LinkedList<RecIntegral>)in.readObject();
        in.close();
        
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        
        linkInteg.forEach((RecIntegral obj) -> {
            model.addRow(new Object[]{obj.getLower(), obj.getUpper(), obj.getStep(), obj.getResult()});
        });
    }
        catch (Exception ex) {
            JOptionPane.showMessageDialog(null, ex);
    }
    }//GEN-LAST:event_jMenuItemLoadbinActionPerformed
