    private void jMenuItemSavetxtActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItemSavetxtActionPerformed
    JFileChooser f = new JFileChooser();
    FileNameExtensionFilter filter = new FileNameExtensionFilter("Text file (*.txt)", "txt");
    f.setFileFilter(filter);
    f.showSaveDialog(null);
    
    File file = f.getSelectedFile();
    
    if(!file.getPath().endsWith(".txt")){
    file = new File(file.getAbsolutePath() + ".txt");
                }
    try(FileWriter writer = new FileWriter(file,false)){
        for(RecIntegral o : linkInteg){
            writer.write(o.getLower() + " " +
                    o.getUpper() + " " + 
                    o.getStep() + " " +
                    o.getResult() + "\n");
        }
        writer.flush();
        writer.close();
        
    } 
    catch(IOException ex){
        JOptionPane.showMessageDialog(null, ex);
    }
    
         
// TODO add your handling code here:
    }//GEN-LAST:event_jMenuItemSavetxtActionPerformed

    private void jMenuItemLoadtxtActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItemLoadtxtActionPerformed
    JFileChooser f = new JFileChooser();
    FileNameExtensionFilter filter = 
            new FileNameExtensionFilter("Text file (*.txt)", "txt");
    f.setFileFilter(filter);
    f.showOpenDialog(null);
    
    File file = f.getSelectedFile(); 
    
    try(BufferedReader reader = new BufferedReader(new FileReader(file))) {
        linkInteg.clear();
        String temp = "";
        while((temp = reader.readLine())!= null){
            String[] part = temp.split(" ");
            linkInteg.add(new RecIntegral(
                Double.parseDouble(part[0]),
                Double.parseDouble(part[1]),
                Double.parseDouble(part[2]),
                Double.parseDouble(part[3])
            ));
        };
    
        reader.close();
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        linkInteg.forEach((RecIntegral obj) -> {
            model.addRow(
            new Object[]{obj.getLower(), 
                obj.getUpper(), 
                obj.getStep(), 
                obj.getResult()
            });
        });
    }
    catch(IOException ex){
        JOptionPane.showMessageDialog(null, ex);
    }
    catch(InvalidException exe){
        JOptionPane.showMessageDialog(null, exe);}
    }//GEN-LAST:event_jMenuItemLoadtxtActionPerformed

