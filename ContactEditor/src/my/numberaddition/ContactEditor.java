    private void jButtonAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAddActionPerformed
       // TODO add your handling code here:
             try {
        // Парсинг введённых значений
        double vp = Double.parseDouble(jTextFieldUpper.getText());
        double np = Double.parseDouble(jTextFieldLower.getText());
        double step = Double.parseDouble(jTextFieldStep.getText());

        // Нормализация границ
        double lower = Math.min(vp, np);
        double upper = Math.max(vp, np);
        
        // Создание объекта с возможной генерацией исключения
        RecIntegral rec = new RecIntegral(upper, lower, step);
        
        // Добавление в коллекцию и таблицу
        linkInteg.add(rec);
        DefaultTableModel Tmodel = (DefaultTableModel)jTable1.getModel();
        Tmodel.addRow(new Object[] {
            rec.getUpper(), 
            rec.getLower(), 
            rec.getStep()
        });
       
    } catch (NumberFormatException e) {
        // Обработка ошибки парсинга числа
        javax.swing.JOptionPane.showMessageDialog(
            this, 
            "Ошибка: введите корректные числовые значения", 
            "Неверный формат ввода", 
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    } catch (InvalidException e) {
        // Обработка нашего пользовательского исключения
        javax.swing.JOptionPane.showMessageDialog(
            this, 
            e.getMessage(), 
            "Некорректные данные", 
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
    }
                 
    }//GEN-LAST:event_jButtonAddActionPerformed

